import type { Health } from './types'

export type AiReadiness = 'checking' | 'demo' | 'invalid' | 'live' | 'unconfigured'

export function getAiReadiness(health: Health | null): AiReadiness {
  if (health === null) return 'checking'
  if (health.ai_mode === 'demo') return 'demo'
  if (health.ai_mode === 'invalid') return 'invalid'
  return health.provider_configured ? 'live' : 'unconfigured'
}

const statusLabels: Record<AiReadiness, string> = {
  checking: 'Checking AI status',
  demo: 'Demo mode',
  invalid: 'AI unavailable',
  live: 'Live AI',
  unconfigured: 'AI needs setup',
}

export function getAiStatusLabel(readiness: AiReadiness): string {
  return statusLabels[readiness]
}

export function getCreationNotice(readiness: AiReadiness): string {
  switch (readiness) {
    case 'invalid':
      return 'The server AI configuration is invalid. Ask the operator to fix it.'
    case 'live':
      return 'Your plan will be generated by live AI on the server.'
    case 'unconfigured':
      return 'Live AI is not available until a valid server-side key and configuration are set.'
    case 'demo':
      return 'Demo mode is active. This plan is generated locally, without live AI.'
    case 'checking':
      return 'Checking AI availability...'
  }
}

export function getWelcomeNotice(readiness: AiReadiness): string {
  switch (readiness) {
    case 'invalid':
      return 'Live planning is unavailable until the server AI configuration is fixed.'
    case 'live':
      return 'Live AI is ready for your plan.'
    case 'unconfigured':
      return 'Live planning needs a valid server-side AI key.'
    case 'demo':
      return 'Demo mode is active. Add a server-side AI key for live planning.'
    case 'checking':
      return 'Checking AI availability...'
  }
}
